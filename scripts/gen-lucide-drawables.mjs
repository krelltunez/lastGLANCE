// Generate Android vector drawables for the full Lucide icon set, so the native
// home-screen widgets can show a chore's icon. Source of truth is lucide-react
// (the exact package the in-app icon registry uses), so the names match the
// values stored in chore.icon with no kebab-case guessing.
//
// Each drawable is named ic_lucide_<snake(PascalName)> using the SAME transform
// the widget applies at runtime (see lucideResName below + SingleChoreWidget.kt).
// Icons are rendered with an opaque black stroke so the widget can tint it to the
// recency color.
//
// lucide exports each icon under several names, and chore.icon can hold any of
// them (ICON_REGISTRY resolves them all). Each icon gets one file, under the name
// canonicalName picks, and every other name gets a one-line resource alias to it,
// so a lookup by any name finds the icon without carrying the file twice.
//
// Run: node scripts/gen-lucide-drawables.mjs
// Output: android/app/src/main/res/drawable/ic_lucide_*.xml
//         android/app/src/main/res/values/lucide_icon_aliases.xml

import { createElement } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import { convert } from 'svg-vectordrawable'
import { mkdir, writeFile, readdir, rm } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { canonicalName, iconGroups } from './lucide-names.mjs'

const RES_DIR = join(
  dirname(fileURLToPath(import.meta.url)),
  '../android/app/src/main/res',
)
const OUT_DIR = join(RES_DIR, 'drawable')
const ALIASES_FILE = join(RES_DIR, 'values/lucide_icon_aliases.xml')

// Snake-case a PascalCase name, char by char (no regex), so the JS generator and
// the Kotlin runtime derive identical resource names.
function lucideResName(pascal) {
  let out = ''
  for (let i = 0; i < pascal.length; i++) {
    const ch = pascal[i]
    const upper = ch >= 'A' && ch <= 'Z'
    if (upper && i > 0) out += '_'
    out += ch.toLowerCase()
  }
  return 'ic_lucide_' + out
}

async function main() {
  const limit = process.argv[2] ? Number(process.argv[2]) : Infinity
  await mkdir(OUT_DIR, { recursive: true })

  // Clean previous generation so removed icons don't linger.
  for (const f of await readdir(OUT_DIR)) {
    if (f.startsWith('ic_lucide_') && f.endsWith('.xml')) {
      await rm(join(OUT_DIR, f))
    }
  }

  const entries = iconGroups().slice(0, limit)
  const aliases = new Map()
  let ok = 0
  let fail = 0
  for (const [Icon, names] of entries) {
    const name = canonicalName(names)
    try {
      const svg = renderToStaticMarkup(
        createElement(Icon, { color: '#000000', size: 24, strokeWidth: 2 }),
      )
      // Lucide puts its stroke styling (width 2, round caps, fill none) on the
      // <svg> root; svg-vectordrawable propagates it to every path.
      const { xml, warnings } = convert(svg, { floatPrecision: 2 })
      for (const w of warnings) console.warn(`WARN ${name}: [${w.code}] ${w.message}`)
      await writeFile(join(OUT_DIR, `${lucideResName(name)}.xml`), xml)
      for (const other of names) {
        const res = lucideResName(other)
        if (res === lucideResName(name)) continue
        if (aliases.has(res) && aliases.get(res) !== lucideResName(name)) {
          throw new Error(`${res} would point at two icons`)
        }
        aliases.set(res, lucideResName(name))
      }
      ok++
    } catch (e) {
      fail++
      console.error(`FAIL ${name}: ${e.message}`)
    }
  }
  await writeFile(
    ALIASES_FILE,
    '<?xml version="1.0" encoding="utf-8"?>\n' +
      '<!-- Generated by scripts/gen-lucide-drawables.mjs. Do not edit. -->\n' +
      '<resources>\n' +
      [...aliases].sort(([a], [b]) => (a < b ? -1 : 1))
        .map(([res, target]) => `    <drawable name="${res}">@drawable/${target}</drawable>\n`)
        .join('') +
      '</resources>\n',
  )
  console.log(`Generated ${ok} drawables and ${aliases.size} aliases (${fail} failed) into ${RES_DIR}`)
}

main()
